import { useState, useEffect } from 'react';
import apiClient from '../../utils/api';
import { toast } from 'sonner';

const MFAVerification = ({ onVerificationComplete, user_id, trust_device: initialTrustDevice = false }) => {
  const [code, setCode] = useState('');
  const [trustDevice, setTrustDevice] = useState(initialTrustDevice);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [timeRemaining, setTimeRemaining] = useState(30);

  // Countdown timer for code expiration
  useEffect(() => {
    const timer = setInterval(() => {
      setTimeRemaining(prev => {
        if (prev <= 1) {
          return 30; // Reset to 30 seconds
        }
        return prev - 1;
      });
    }, 1000);

    return () => clearInterval(timer);
  }, []);

  const handleVerify = async () => {
    try {
      setLoading(true);
      setError('');
      
      if (code.length !== 6) {
        setError('Please enter a 6-digit code');
        setLoading(false);
        return;
      }
      
      const response = await apiClient.post('/auth/mfa/verify', {
        code,
        trust_device: trustDevice,
        user_id: user_id
      });
      
      toast.success('MFA verified successfully');
      
      if (onVerificationComplete) {
        onVerificationComplete(response.data);
      }
    } catch (err) {
      console.error('MFA verification failed:', err);
      setError('Invalid MFA code. Please try again.');
      toast.error('Invalid MFA code');
      setCode('');
    } finally {
      setLoading(false);
    }
  };

  const handleResendCode = () => {
    // Note: For TOTP, codes are generated by the authenticator app
    // This is a placeholder for future SMS-based MFA
    toast.info('Generate a new code in your authenticator app');
  };

  const handleUseBackupCode = () => {
    // Placeholder for backup code recovery
    toast.info('Contact support for backup code recovery');
  };

  return (
    <div className="mfa-verification">
      <div className="max-w-md mx-auto bg-white border border-border p-8">
        <div className="text-center mb-6">
          <div className="w-16 h-16 bg-primary rounded-full flex items-center justify-center mx-auto mb-4">
            <svg className="w-8 h-8 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 15v2m-6 4h12a2 2 0 002 2v6a2 2 0 002-2H6a2 2 0 00-2-2v-6a2 2 0 002-2h12a2 2 0 002 2zm-2 2h.01M17 16H4m4 4h5M2 6h12a2 2 0 002-2V6a2 2 0 00-2-2H6a2 2 0 00-2 2v12a2 2 0 002 2z" />
            </svg>
          </div>
          <h2 className="text-2xl font-bold text-primary mb-2">Enter MFA Code</h2>
          <p className="text-muted">
            Open your authenticator app and enter the 6-digit code
          </p>
        </div>
        
        <div className="mb-6">
          <div className="flex justify-between items-center mb-2">
            <label className="font-semibold">Authentication Code</label>
            <span className="text-sm text-muted">
              Code refreshes in {timeRemaining}s
            </span>
          </div>
          <input
            type="text"
            value={code}
            onChange={(e) => setCode(e.target.value)}
            placeholder="123456"
            maxLength={6}
            className="w-full border border-border px-4 py-3 text-center text-2xl tracking-widest focus:outline-none focus:ring-2 focus:ring-primary"
            autoFocus
          />
          {error && <p className="text-red-500 text-sm mt-2">{error}</p>}
        </div>
        
        <div className="mb-6">
          <label className="flex items-center space-x-2 cursor-pointer">
            <input
              type="checkbox"
              checked={trustDevice}
              onChange={(e) => setTrustDevice(e.target.checked)}
              className="w-4 h-4 text-primary"
            />
            <span className="text-sm">
              Trust this device for 30 days
            </span>
          </label>
          <p className="text-xs text-muted mt-1">
            When checked, you won't be asked for MFA on this device for 30 days
          </p>
        </div>
        
        <button
          onClick={handleVerify}
          disabled={loading || code.length !== 6}
          className="w-full bg-primary text-white px-6 py-3 font-bold tracking-wide border border-primary hover:bg-[#333333] transition-all disabled:opacity-50"
        >
          {loading ? 'Verifying...' : 'Verify'}
        </button>
        
        <div className="mt-6 pt-6 border-t border-border">
          <p className="text-sm text-muted mb-2">Having trouble?</p>
          <div className="space-y-2">
            <button
              onClick={handleResendCode}
              className="text-sm text-primary hover:underline w-full text-left"
            >
              Generate new code in authenticator app
            </button>
            <button
              onClick={handleUseBackupCode}
              className="text-sm text-primary hover:underline w-full text-left"
            >
              Use backup code
            </button>
          </div>
        </div>
        
        <div className="mt-4 p-4 bg-blue-50 border border-blue-200">
          <h4 className="font-semibold text-blue-800 mb-2">Need Help?</h4>
          <ul className="text-sm text-blue-800 space-y-1">
            <li>• Make sure your device's time is synchronized</li>
            <li>• Check that you're using the correct authenticator app</li>
            <li>• Contact support if you lost your authenticator device</li>
          </ul>
        </div>
      </div>
    </div>
  );
};

export default MFAVerification;